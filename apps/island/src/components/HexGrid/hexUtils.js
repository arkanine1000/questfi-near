/**
 * Hex math utilities for pointy-top hexagonal grid using axial coordinates (q, r).
 */

/**
 * Convert axial coordinates to pixel position for SVG placement.
 * Pointy-top hex layout.
 */
export function axialToPixel(q, r, hexSize) {
  const x = hexSize * (Math.sqrt(3) * q + (Math.sqrt(3) / 2) * r);
  const y = hexSize * ((3 / 2) * r);
  return { x, y };
}

/**
 * Returns the 6 vertex points string for a pointy-top hex polygon.
 */
export function getHexPoints(hexSize) {
  const points = [];
  for (let i = 0; i < 6; i++) {
    const angleDeg = 60 * i - 30;
    const angleRad = (Math.PI / 180) * angleDeg;
    points.push(`${hexSize * Math.cos(angleRad)},${hexSize * Math.sin(angleRad)}`);
  }
  return points.join(' ');
}

/**
 * Returns the 6 neighboring axial coordinates.
 */
export function getHexNeighbors(q, r) {
  return [
    { q: q + 1, r: r },
    { q: q - 1, r: r },
    { q: q, r: r + 1 },
    { q: q, r: r - 1 },
    { q: q + 1, r: r - 1 },
    { q: q - 1, r: r + 1 },
  ];
}

